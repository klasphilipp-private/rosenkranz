(() => {
  const page = decodeURIComponent(location.pathname.split('/').pop() || '');
  const documents = window.RosenkranzModelDocuments[page];
  const target = document.querySelector('.model-detail .wrap');
  if (!target || !documents?.length) return;
  const section = document.createElement('section');
  section.className = 'model-documents';
  section.setAttribute('aria-label', 'Preislisten und Prospekte');
  const heading = document.createElement('h2'); heading.textContent = 'Preislisten & Prospekte';
  const intro = document.createElement('p'); intro.textContent = 'Alle Informationen zum Fahrzeug und zur Ausstattung auf einen Blick. Dokumente öffnen oder direkt herunterladen.';
  const list = document.createElement('div'); list.className = 'model-documents-list';
  documents.forEach(doc => {
    const card = document.createElement('article'); card.className = 'model-document';
    const name = document.createElement('strong'); name.textContent = doc.name;
    const date = document.createElement('small'); date.textContent = `Dokumentstand ${doc.date} · PDF`;
    const links = document.createElement('div'); links.className = 'model-document-links';
    const open = document.createElement('a'); open.href = doc.path; open.target = '_blank'; open.rel = 'noopener'; open.textContent = 'Ansehen ↗'; open.setAttribute('aria-label', `${doc.name} in neuem Tab öffnen`);
    const download = document.createElement('a'); download.href = doc.path; download.download = ''; download.textContent = 'Herunterladen ↓'; download.setAttribute('aria-label', `${doc.name} herunterladen`);
    links.append(open, download); card.append(name, date, links); list.append(card);
  });
  section.append(heading, intro, list); target.append(section);
})();
